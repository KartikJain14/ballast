"""
make replay -> python scripts/replay.py

Runs the full year through the simulator for every registered policy and
writes a scoreboard to reports/scoreboard.json + docs/RESULTS.md. This is the
brief's required full-year comparison across all baselines, Ballast, and the
oracle (Ballast/oracle are added in Phase 4; this script runs whatever is
registered in `all_policies()` so it stays correct as new policies land).
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engine.config import EngineConfig  # noqa: E402
from engine.data import load_raw, DEFAULT_CSV_PATH  # noqa: E402
from engine.simulator.engine import Simulator  # noqa: E402
from engine.policy.baselines import (  # noqa: E402
    AllCashPolicy, StaticBufferPolicy, FixedPctOfGrossPolicy,
    MovingAverageKSigmaPolicy, MillerOrrPolicy,
)


def all_policies():
    policies = [
        AllCashPolicy(),
        StaticBufferPolicy(50_000_000),
        FixedPctOfGrossPolicy(0.5),
        MovingAverageKSigmaPolicy(k=2.0),
        MillerOrrPolicy(),
    ]
    try:
        from engine.policy.ballast_policy import BallastPolicy
        policies.append(BallastPolicy())
    except ImportError:
        pass
    try:
        from engine.policy.oracle import OraclePolicy
        policies.append(OraclePolicy())
    except ImportError:
        pass
    return policies


def main():
    df = load_raw(DEFAULT_CSV_PATH)
    cfg = EngineConfig.full_4tier()
    sim = Simulator(df, cfg)

    results = {}
    for policy in all_policies():
        t0 = time.time()
        res = sim.run(policy)
        dt = time.time() - t0
        results[res.policy_name] = {**res.summary, "runtime_sec": dt}
        print(f"{res.policy_name:25s} runtime={dt:6.2f}s  "
              f"net_interest=${res.summary['net_interest_earned']:>14,.0f}  "
              f"fees=${res.summary['total_fees_paid']:>14,.0f}  "
              f"od_hours={res.summary['overdraft_hours']:5d}  "
              f"breaks={res.summary['n_tier_breaks']:3d}")

    (ROOT / "reports").mkdir(exist_ok=True)
    with open(ROOT / "reports" / "scoreboard.json", "w") as f:
        json.dump(results, f, indent=2, default=str)

    best_naive = min(
        (k for k in results if k not in ("ballast", "oracle")),
        key=lambda k: results[k]["total_cost_of_liquidity"],
    )
    write_results_md(results, best_naive)


def write_results_md(results: dict, best_naive: str):
    lines = ["# Results — Full-Year Scoreboard\n",
             "Auto-generated by `make replay` (`scripts/replay.py`). Every number here is "
             "computed by running the simulator against `data/treasury_4tier_dataset.csv`.\n",
             "| Policy | Net interest earned | Total fees paid | Total cost of liquidity | "
             "Overdraft hours | Overdraft events | Tier breaks | Four-eyes events |",
             "|---|---|---|---|---|---|---|---|"]
    for name, r in results.items():
        lines.append(
            f"| {name} | ${r['net_interest_earned']:,.0f} | ${r['total_fees_paid']:,.0f} | "
            f"${r['total_cost_of_liquidity']:,.0f} | {r['overdraft_hours']} | "
            f"{r['overdraft_event_count']} | {r['n_tier_breaks']} | {r['four_eyes_events']} |"
        )
    lines.append(f"\n**Best naive baseline (lowest total cost of liquidity): `{best_naive}`.**\n")
    if "ballast" in results:
        b = results["ballast"]
        base = results[best_naive]
        lines.append(f"Ballast vs. best naive: "
                      f"${base['total_cost_of_liquidity'] - b['total_cost_of_liquidity']:,.0f} "
                      f"lower total cost of liquidity.\n")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
